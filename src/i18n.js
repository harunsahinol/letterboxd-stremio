export const fmt = (s, vars = {}) => s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));

export function addonStrings(lang) {
  return ADDON[lang] || ADDON[DEFAULT_LANG];
}

export function formatRating(r, lang) {
  try {
    const locale = { zh: "zh-CN" }[lang] || lang;
    return new Intl.NumberFormat(locale, { minimumFractionDigits: 1, maximumFractionDigits: 1 }).format(r);
  } catch {
    return r.toFixed(1);
  }
}
